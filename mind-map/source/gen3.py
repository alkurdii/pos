import re, html
from gen import page, CSS, FIT_JS, COLORS

def esc(s):
    return html.escape(s, quote=False)

AR_DIGITS = "٠١٢٣٤٥٦٧٨٩"

def node_html(text, level, step=None):
    if "::" in text:
        ar, note = [t.strip() for t in text.split("::", 1)]
    else:
        ar, note = text.strip(), ""
    badge = f'<em class="badge">{step}</em>' if step else ""
    out = f'<span class="n l{min(level,3)}">{badge}<b>{esc(ar)}</b>'
    if note:
        out += f'<i>{esc(note)}</i>'
    return out + "</span>"

def parse(spec):
    lines = [l for l in spec.strip("\n").split("\n") if l.strip()]
    root, stack, right, left, side = None, [], [], [], "right"
    for l in lines:
        if l.strip() == "---":
            side = "left"; continue
        ind = (len(l) - len(l.lstrip(" "))) // 2
        t = l.strip()
        color = None
        m = re.match(r"^\[(\w+)\]\s*(.*)$", t)
        if m:
            color, t = m.group(1), m.group(2)
        on, step = False, None
        m = re.match(r"^\*([٠-٩])?\s*(.*)$", t)
        if m:
            on, step, t = True, m.group(1), m.group(2)
        nd = {"text": t, "color": color, "kids": [], "on": on, "step": step}
        if ind == 0:
            root = nd; stack = [nd]; continue
        stack = stack[:ind]
        stack[-1]["kids"].append(nd)
        if ind == 1:
            (right if side == "right" else left).append(nd)
        stack.append(nd)
    return root, right, left

def tree_html(nodes, level):
    if not nodes:
        return ""
    out = "<ul>"
    for nd in nodes:
        style = f' style="--c:{COLORS[nd["color"]]}"' if nd["color"] else ""
        cls = ' class="on"' if nd["on"] else ""
        out += f"<li{style}{cls}>" + node_html(nd["text"], level, nd["step"]) + tree_html(nd["kids"], level + 1) + "</li>"
    return out + "</ul>"

def tree_block(spec, hl=False):
    root, right, left = parse(spec)
    rc = COLORS[root["color"]] if root["color"] else "#111827"
    return f'''<div class="fit"><div class="bi{' hlmode' if hl else ''}">
    <div class="side ltr">{tree_html(right, 1)}</div>
    <div class="rootwrap" style="--c:{rc}">{node_html(root["text"], 0, root["step"])}</div>
    <div class="side rtl">{tree_html(left, 1)}</div></div></div>'''

def mindmap(title, sub, spec):
    return page(f'<header><h2>{esc(title)}</h2><p>{esc(sub)}</p></header>{tree_block(spec)}')


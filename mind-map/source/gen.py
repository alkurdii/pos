# -*- coding: utf-8 -*-
"""Builds the mind-map HTML (Kurdish Badini + Arabic) for al-Ajurrumiyya & Mulhat al-I'rab."""
import html, re

COLORS = {
    "raf": "#1d4ed8", "nasb": "#15803d", "khafd": "#c2410c", "jazm": "#b91c1c",
    "c1": "#7c3aed", "c2": "#0e7490", "c3": "#be185d", "c4": "#a16207",
    "c5": "#4338ca", "c6": "#0f766e", "c7": "#9d174d", "c8": "#57534e",
    "c9": "#0369a1", "c10": "#6d28d9", "c11": "#b45309", "c12": "#047857",
    "c13": "#9f1239", "c14": "#3f6212",
}

def esc(s):
    return html.escape(s, quote=False)

def node_html(text, level):
    if "::" in text:
        ar, ku = [t.strip() for t in text.split("::", 1)]
    else:
        ar, ku = text.strip(), ""
    out = f'<span class="n l{min(level,3)}"><b>{esc(ar)}</b>'
    if ku:
        out += f'<i>{esc(ku)}</i>'
    return out + "</span>"

def parse(spec):
    """indented spec -> (root, right_children, left_children). node = dict(text,color,kids)."""
    lines = [l for l in spec.strip("\n").split("\n") if l.strip()]
    root = None
    stack = []
    right, left, side = [], [], "right"
    for l in lines:
        if l.strip() == "---":
            side = "left"; continue
        ind = (len(l) - len(l.lstrip(" "))) // 2
        t = l.strip()
        color = None
        m = re.match(r"^\[(\w+)\]\s*(.*)$", t)
        if m:
            color, t = m.group(1), m.group(2)
        nd = {"text": t, "color": color, "kids": []}
        if ind == 0:
            root = nd; stack = [nd]; continue
        stack = stack[:ind]
        stack[-1]["kids"].append(nd)
        if ind == 1:
            (right if side == "right" else left).append(nd)
        stack.append(nd)
    root["kids"] = []
    return root, right, left

def tree_html(nodes, level, inherited=None):
    if not nodes:
        return ""
    out = "<ul>"
    for nd in nodes:
        c = nd["color"] or inherited
        style = f' style="--c:{COLORS[c]}"' if nd["color"] else ""
        out += f"<li{style}>" + node_html(nd["text"], level) + tree_html(nd["kids"], level + 1, c) + "</li>"
    return out + "</ul>"

def mindmap(title, sub, spec, root_color="#111827"):
    root, right, left = parse(spec)
    m = re.match(r"^\[(\w+)\]\s*", root["text"])
    rc = root_color
    if root["color"]:
        rc = COLORS[root["color"]]
    return f'''
<section class="page">
  <header><h2>{esc(title)}</h2><p>{esc(sub)}</p></header>
  <div class="fit"><div class="bi">
    <div class="side ltr">{tree_html(right, 1)}</div>
    <div class="rootwrap" style="--c:{rc}">{node_html(root["text"], 0)}</div>
    <div class="side rtl">{tree_html(left, 1)}</div>
  </div></div>
  <footer>{{PAGENO}}</footer>
</section>'''


def cards_pages(items, title, subs, per):
    out = []
    chunks = [items[i:i+per] for i in range(0, len(items), per)]
    for ci, ch in enumerate(chunks):
        cards = ""
        for (sent, tag, words) in ch:
            rows = "".join(f'<tr><td class="w">{w}</td><td class="ar">{a}</td><td class="kn">{k}</td></tr>' for w, a, k in words)
            cards += f'<div class="excard"><div class="exh"><span class="s">{sent}</span><span class="tag">{tag}</span></div><table>{rows}</table></div>'
        n = len(chunks)
        num = f" ({'١٢٣٤'[ci]}/{'١٢٣٤'[n-1]})" if n > 1 else ""
        out.append(page(f'<header><h2>{title}{num}</h2><p>{subs[ci]}</p></header><div class="exgrid">{cards}</div>'))
    return out

